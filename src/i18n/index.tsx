const detect = (): Language => {
  const code = Intl.DateTimeFormat()
    .resolvedOptions()
    .locale.toLowerCase()
    .split(/[-_]/)[0];
  return languages.some(item => item.code === code) ? (code as Language) : 'en';
};
type Context = {
  language: Language;
  setLanguage: (language: Language) => Promise<void>;
};
const LanguageContext = createContext<Context | undefined>(undefined);
export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, update] = useState<Language>(detect);
  runtimeLanguage = language;
  useEffect(() => {
    void AsyncStorage.getItem('language').then(saved => {
      if (languages.some(item => item.code === saved))
        update(saved as Language);
    });
  }, []);
  const setLanguage = async (next: Language) => {
    runtimeLanguage = next;
    update(next);
    await AsyncStorage.setItem('language', next);
  };
  return (
    <LanguageContext.Provider value={{ language, setLanguage }}>
      {children}
    </LanguageContext.Provider>
  );
}
